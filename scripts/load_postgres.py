
"""
PostgreSQL Data Loader — Seoul Bike AutoML

Purpose:
    Load the cleaned and merged bike-sharing dataset
    into PostgreSQL using Pandas and SQLAlchemy.

Input:
    data/processed/bike_weather_merged.csv

Output:
    PostgreSQL table: bike_demand_cleaned

Features:
    - Dynamic schema creation from the DataFrame
    - Transactional data loading
    - Duplicate timestamp validation
    - Idempotent replacement of historical records
    - Database verification and basic SQL analysis
"""

import os
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import URL


# Define paths relative to the project root.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = (
    PROJECT_ROOT / "data" / "processed"
    / "bike_weather_merged.csv"
)

TABLE_NAME = "bike_demand_cleaned"

# Load PostgreSQL connection settings from the project .env file.
load_dotenv(PROJECT_ROOT / ".env")


def get_engine():
    """
    Create a SQLAlchemy connection engine for PostgreSQL.

    Returns:
        Engine: SQLAlchemy database engine.
    """

    # Retrieve credentials without hardcoding passwords.
    user = os.environ["POSTGRES_USER"]
    password = os.environ["POSTGRES_PASSWORD"]
    database = os.environ["POSTGRES_DB"]
    port = int(os.getenv("POSTGRES_PORT", "5433"))

    # URL.create safely handles special characters in passwords.
    database_url = URL.create(
        drivername="postgresql+psycopg2",
        username=user,
        password=password,
        # Use localhost on the Mac and the Docker service name inside Airflow.
        host=os.getenv("POSTGRES_HOST", "127.0.0.1"),
        port=port,
        database=database,
    )

    return create_engine(database_url, pool_pre_ping=True)


def load_dataframe():
    """
    Read and validate the processed CSV dataset.

    Returns:
        pd.DataFrame: Cleaned dataset ready for database loading.
    """

    # Read the output generated by prepare_data.py.
    # Parse timestamp as datetime for PostgreSQL compatibility.
    df = pd.read_csv(
        DATA_PATH,
        parse_dates=["timestamp"],
    )

    # Each timestamp should represent exactly one hourly observation.
    if df["timestamp"].isna().any():
        raise ValueError("Missing timestamps detected.")

    if df["timestamp"].duplicated().any():
        raise ValueError("Duplicate timestamps detected.")

    # Prevent incomplete records from entering the database.
    if df.isna().any().any():
        raise ValueError("Missing values detected in processed data.")

    return df


def upload_to_postgres(df, engine):
    """
    Upload the DataFrame to PostgreSQL.

    Existing records are replaced within a single transaction,
    preventing duplicate rows on repeated pipeline runs.

    Args:
        df (pd.DataFrame): DataFrame to upload.
        engine: SQLAlchemy database engine.
    """

    # A transaction ensures that the replacement either completes
    # successfully or rolls back if a database error occurs.
    with engine.begin() as connection:

        # Check whether the destination table already exists.
        if inspect(connection).has_table(TABLE_NAME):

            # Remove previous historical records before reloading.
            # This is appropriate for our small, fixed historical dataset.
            connection.execute(
                text("DELETE FROM bike_demand_cleaned")
            )

        # Create the table automatically if it does not exist.
        # Pandas infers SQL column types from the DataFrame.
        df.to_sql(
            TABLE_NAME,
            con=connection,
            if_exists="append",
            index=False,
            chunksize=500,
            method="multi",
        )

        # Enforce one record per timestamp at the database level.
        connection.execute(
            text(
                "CREATE UNIQUE INDEX IF NOT EXISTS "
                "idx_bike_demand_timestamp "
                "ON bike_demand_cleaned (timestamp)"
            )
        )

    print("Data uploaded successfully.")


def verify_database(engine):
    """
    Verify the stored data and run a simple SQL analysis.
    """

    with engine.connect() as connection:

        # Check the number of successfully stored observations.
        row_count = connection.execute(
            text("SELECT COUNT(*) FROM bike_demand_cleaned")
        ).scalar_one()

        # Calculate average hourly rentals from PostgreSQL.
        # Original column names are preserved, so SQL identifiers
        # containing spaces must be enclosed in double quotes.
        avg_rentals = connection.execute(
            text(
                'SELECT AVG("Rented Bike Count") '
                'FROM bike_demand_cleaned'
            )
        ).scalar_one()

        print("\n=== DATABASE VERIFICATION ===")
        print("Stored rows:", row_count)
        print("Average hourly rentals:", round(avg_rentals, 2))


def main():
    """Execute the complete database loading workflow."""

    # Step 1: Read the processed DataFrame.
    df = load_dataframe()

    print("DataFrame shape:", df.shape)

    # Step 2: Connect to PostgreSQL.
    engine = get_engine()

    # Step 3: Upload records into the database.
    upload_to_postgres(df, engine)

    # Step 4: Verify stored records through SQL queries.
    verify_database(engine)

    # Release database connections.
    engine.dispose()


if __name__ == "__main__":
    main()
